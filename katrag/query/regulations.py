_GRAD_LEVEL = ("ปริญญาโท", "ปริญญาเอก", "ป.โท", "ป.เอก", "บัณฑิตศึกษา", "มหาบัณฑิต", "ดุษฎีบัณฑิต")


_GPA_NUM_RE = re.compile(r"(?:เกรด|gpa|gpax|ค่าระดับคะแนน)[^\d]{0,20}?([0-4]\.\d{1,2})", re.IGNORECASE)


def _honors_gpa(text: str) -> float | None:
    """เกรดเฉลี่ยในคำถามเกียรตินิยม — รับเลขทศนิยม 2 ตำแหน่งลอย ๆ ได้ ("จบด้วย 3.45")."""
    g = stated_gpa(text)
    if g is not None:
        return g
    m = re.search(r"(?<![\d.])([0-4]\.\d{2})(?![\d])", text)
    return float(m.group(1)) if m else None


def stated_gpa(text: str) -> float | None:
    """เกรดเฉลี่ยที่ผู้ถามบอกมา เช่น "ได้เกรดเฉลี่ย 1.80" (None = ไม่ได้ระบุตัวเลข)."""
    m = _GPA_NUM_RE.search(text)
    return float(m.group(1)) if m else None


_FINAL_YEAR_RE = re.compile(r"ปีสุดท้าย|เทอมสุดท้าย|ภาคสุดท้าย|ใกล้จบ|จะจบแล้ว|ก่อนจบ")


def _final_year_load(text: str) -> int | None:
    """หน่วยกิตที่ชั้นปีสุดท้ายจะลงในภาคเดียว (None = ไม่ใช่คำถามแบบนี้)."""
    if not _FINAL_YEAR_RE.search(text) or not re.search(r"ลง|เทอมเดียว|ภาคเดียว|ทีเดียว", text):
        return None
    m = re.search(r"(\d{1,2})\s*หน่วยกิต", text)
    return int(m.group(1)) if m else None


def detect_regulation_topic(question: str) -> str | None:
    """หัวข้อข้อบังคับที่คำถามถามถึง (None = ไม่ใช่คำถามข้อบังคับ)."""
    raw = re.sub(r"^\s*หลักสูตร\s+[A-Za-z_]+\s*[:：]\s*", "", question)
    q = raw.lower()
    if any(w in raw for w in _GRAD_LEVEL):
        return None  # ข้อบังคับนี้เป็นของปริญญาตรีเท่านั้น
    if "อาจารย์" in raw:
        return None  # เช่น ประวัติอาจารย์ "(เกียรตินิยมอันดับหนึ่ง)"
    names_term = re.search(r"ปี\s*(?:ที่)?\s*[1-4]|ปี(?:หนึ่ง|สอง|สาม|สี่)|เทอม\s*[12]|ภาค(?:การศึกษา)?(?:ที่)?\s*[12]", raw)
    # "เกรดเฉลี่ยต่ำกว่า 2.00 จะเกิดอะไรขึ้น" — ไม่ได้พูดว่าภาคทัณฑ์/พ้นสภาพ แต่ถามผลของเกรดต่ำ
    low = any(w in q for w in ("ต่ำกว่า", "ไม่ถึง", "น้อยกว่า", "ไม่ถึง"))
    gpa = any(w in q for w in ("เกรด", "gpa", "gpax", "ค่าระดับคะแนน"))
    asks_effect = not any(w in q for w in ("จบ", "สำเร็จการศึกษา", "เกียรตินิยม", "ภาคทัณฑ์", "พ้นสภาพ", "รีไทร์"))
    if low and gpa and asks_effect:
        return "low_gpa"
    # "เทอมแรกได้เกรดเฉลี่ย 1.80 จะเกิดอะไรขึ้น", "เกรดเฉลี่ยสะสม 0.95 ยังเรียนต่อได้ไหม"
    g = stated_gpa(raw)
    if g is not None and g < 2.0 and asks_effect:
        return "low_gpa"
    # "จบด้วย 3.45 ได้อันดับ 1 หรืออันดับ 2" — ถามอันดับเกียรตินิยมโดยไม่พูดคำว่าเกียรตินิยม
    if re.search(r"อันดับ\s*(?:1|2|หนึ่ง|สอง)", raw) and (_honors_gpa(raw) is not None or gpa):
        return "honors"  # "อันดับสองต้องได้ GPA เท่าไหร่"
    # "ปีสุดท้ายเหลือ 25 หน่วยกิต ลงเทอมเดียวได้ไหม" — ข้อยกเว้นเพดาน 22 ของชั้นปีสุดท้าย
    if _final_year_load(raw) is not None:
        return "registration"
    # "ลง 25 หน่วยกิตได้ไหม" — ระบุจำนวนหน่วยกิตที่จะลงในภาคเดียว (ไม่ได้ระบุปี/เทอมของแผน)
    if re.search(r"ลง\s*(?:ทะเบียน|เรียน)?\s*\d{1,2}\s*หน่วยกิต", raw) and not names_term:
        return "registration"
    for key, must, also in _RULES:
        if any(w in q for w in must) and (not also or any(w in q for w in also)):
            if key == "registration" and names_term:
                return None  # "ปี 1 เทอม 1 ลงทะเบียนกี่หน่วยกิต" ถามตามแผน ไม่ใช่เพดานการลงทะเบียน
            return key
    return None


def try_regulation(conn: sqlite3.Connection, question: str):
    from katrag.query.structured_query import StructuredResult

    key = detect_regulation_topic(question)
    if key is None:
        return StructuredResult(False, "", "", "none")
    topic = TOPICS[key]
    doc = conn.execute(
        "SELECT d.document_id FROM document d JOIN curriculum_version cv ON cv.version_id = d.version_id "
        "WHERE cv.program = 'AIT' AND cv.curriculum_year = 2566 AND d.degree_level = 'bachelor'"
    ).fetchone()
    pages_txt = ", ".join(str(p) for p in topic.pages)
    lines = [f"{topic.title} ตาม{SOURCE_LABEL} หน้า {pages_txt}", "(ข้อบังคับของสถาบัน ใช้กับทุกหลักสูตรปริญญาตรี)"]
    n = _final_year_load(question)
    if key == "registration" and n is not None:
        if n <= 22:
            lines.insert(0, f"คำตอบ: ได้ — {n} หน่วยกิตไม่เกินเพดานภาคปกติ 22 หน่วยกิต")
        elif n <= 27:
            lines.insert(0, f"คำตอบ: ได้ — {n} หน่วยกิตเกิน 22 แต่ชั้นปีสุดท้ายที่ต้องลงเกิน 22 หน่วยกิตเพื่อสำเร็จการศึกษา "
                            "ลงได้ไม่เกิน 27 หน่วยกิต (ข้อยกเว้นในข้อบังคับ)")
        else:
            lines.insert(0, f"คำตอบ: ไม่ได้ — {n} หน่วยกิตเกิน 27 หน่วยกิต ซึ่งเป็นเพดานสูงสุดแม้เป็นชั้นปีสุดท้าย")
    if key == "registration" and n is None:
        m = re.search(r"(\d{1,2})\s*หน่วยกิต", question)
        if m:
            k = int(m.group(1))
            if any(w in question.lower() for w in _SUMMER_WORDS):
                lines.insert(0, f"คำตอบ: {'ได้' if k <= 9 else 'ไม่ได้'} — ภาคฤดูร้อนลงทะเบียนได้ไม่เกิน 9 หน่วยกิต"
                                + (f" ({k} หน่วยกิตเกินเพดาน)" if k > 9 else ""))
            elif k < 9 or k > 22:
                lines.insert(0, f"คำตอบ: ไม่ได้ — ภาคปกติต้องลงไม่น้อยกว่า 9 และไม่เกิน 22 หน่วยกิต ({k} หน่วยกิต"
                                + (" ต่ำกว่าขั้นต่ำ)" if k < 9 else " เกินเพดาน)")
                                + " ยกเว้นกรณีชั้นปีสุดท้ายตามข้อยกเว้นด้านล่าง")
            else:
                lines.insert(0, f"คำตอบ: ได้ — {k} หน่วยกิตอยู่ในช่วง 9–22 หน่วยกิตของภาคปกติ")
    hg = _honors_gpa(question) if key == "honors" else None
    if hg is not None:
        if hg >= 3.75:
            lines.insert(0, f"คำตอบ: เกรดเฉลี่ยสะสม {hg:.2f} ถึงเกณฑ์อันดับ 1 (3.50) และถึงเกณฑ์เกรดของเหรียญทอง (3.75) "
                            "แต่เหรียญทองต้องเป็นเกรดสูงสุดของรุ่นในหลักสูตรด้วย")
        elif hg >= 3.5:
            lines.insert(0, f"คำตอบ: เกรดเฉลี่ยสะสม {hg:.2f} ได้เกียรตินิยมอันดับ 1 (ไม่ต่ำกว่า 3.50) แต่ยังไม่ถึงเกณฑ์เหรียญทอง 3.75")
        elif hg >= 3.25:
            lines.insert(0, f"คำตอบ: เกรดเฉลี่ยสะสม {hg:.2f} ได้เกียรตินิยมอันดับ 2 (ไม่ต่ำกว่า 3.25) ยังไม่ถึงอันดับ 1 ซึ่งต้อง 3.50")
        else:
            lines.insert(0, f"คำตอบ: เกรดเฉลี่ยสะสม {hg:.2f} ไม่ได้เกียรตินิยม (อันดับ 2 ต้องไม่ต่ำกว่า 3.25)")
        lines[0] += " — และต้องผ่านเงื่อนไขทั่วไปข้อ 36.1 ด้านล่าง"
    g = stated_gpa(question)
    if key == "low_gpa" and g is not None and g < 2.0:
        if g < 1.0:
            lines.insert(0, f"คำตอบ: เกรดเฉลี่ยสะสม {g:.2f} ต่ำกว่า 1.00 → พ้นสภาพนักศึกษา (ข้อ 43.11)")
        else:
            lines.insert(0, f"คำตอบ: เกรดเฉลี่ย {g:.2f} ต่ำกว่า 2.00 → ถูกภาคทัณฑ์ (ข้อ 31) "
                            "ถ้าภาคถัดไปเกรดเฉลี่ยประจำภาคยังต่ำกว่า 2.00 จะพ้นสภาพ (ข้อ 43.10)")
    lines += [f"- {ln}" for ln in topic.lines]
    pages = [(doc[0], p, "ข้อบังคับการศึกษาระดับปริญญาตรี") for p in topic.pages] if doc else []
    return StructuredResult(True, "\n".join(lines), SOURCE_LABEL, "regulation", pages=pages)
