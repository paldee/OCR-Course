"""ชุดคำถามทดสอบ 3 ระดับ (Easy / Medium / Hard) + ground truth สำหรับตรวจ.

หลักสำคัญ (anti-leak): ฟิลด์ ``expected`` ใช้ *เฉพาะตอนตรวจ* เท่านั้น
ตัวรัน (qa_eval.py) จะส่งไปที่ /ask แค่ ``question`` + ``program``
ไม่มีการส่ง expected เข้า prompt/LLM เด็ดขาด

``check`` = คำ/ตัวเลขที่ต้องปรากฏในคำตอบ (ใช้ตรวจอัตโนมัติแบบ substring)
``forbid`` = คำที่ไม่ควรปรากฏ (ใช้จับคำตอบผิดที่พบบ่อย)
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class QAItem:
    qid: str
    level: str                     # easy | medium | hard
    program: str                   # "" = ไม่ระบุหลักสูตร
    question: str
    expected: str                  # เฉลย (สำหรับผู้ตรวจ — ไม่ส่งเข้าระบบ)
    reference: str                 # อ้างอิงหน้า/หัวข้อ
    check: tuple[str, ...] = ()    # ต้องมีคำเหล่านี้ในคำตอบ
    forbid: tuple[str, ...] = ()   # ต้องไม่มีคำเหล่านี้


